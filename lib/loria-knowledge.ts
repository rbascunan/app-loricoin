// Funcion para detectar el tema de la pregunta
export function detectTopic(message: string): string {
  const lowerMessage = message.toLowerCase()
  
  // Detectar preguntas de padres
  const parentKeywords = ["mi hijo", "mis hijos", "como padre", "como madre", "familia", "ensenar", "enseñar", "edad", "mesada sugerida"]
  if (parentKeywords.some(k => lowerMessage.includes(k))) {
    if (lowerMessage.includes("edad") || lowerMessage.includes("anos") || lowerMessage.includes("años")) {
      return "padresEdades"
    }
    return "padresConsejos"
  }
  
  // Temas especificos
  if (lowerMessage.includes("que es el dinero") || lowerMessage.includes("de donde viene")) return "dinero"
  if (lowerMessage.includes("ingreso")) return "ingresos"
  if (lowerMessage.includes("egreso") || lowerMessage.includes("gasto")) return "egresos"
  if (lowerMessage.includes("ahorro") || lowerMessage.includes("ahorrar") || lowerMessage.includes("guardar dinero")) return "ahorro"
  if (lowerMessage.includes("meta") || lowerMessage.includes("objetivo")) return "metas"
  if (lowerMessage.includes("necesidad") || lowerMessage.includes("deseo") || lowerMessage.includes("necesito")) return "necesidadVsDeseo"
  if (lowerMessage.includes("inversion") || lowerMessage.includes("invertir")) return "inversion"
  if (lowerMessage.includes("administra") || lowerMessage.includes("dividir") || lowerMessage.includes("organiz")) return "administracion"
  if (lowerMessage.includes("habito") || lowerMessage.includes("costumbre")) return "habitos"
  if (lowerMessage.includes("ejercicio") || lowerMessage.includes("practica") || lowerMessage.includes("matematica")) return "ejercicios"
  if (lowerMessage.includes("actividad") || lowerMessage.includes("juego") || lowerMessage.includes("jugar")) return "actividades"
  if (lowerMessage.includes("dato curioso") || lowerMessage.includes("sabias que")) return "datosCuriosos"
  if (lowerMessage.includes("emprendimiento") || lowerMessage.includes("negocio") || lowerMessage.includes("vender")) return "emprendimiento"
  if (lowerMessage.includes("loricoin") || lowerMessage.includes("lori coin") || lowerMessage.includes("recompensa")) return "loricoins"
  if (lowerMessage.includes("presupuesto")) return "administracion"
  
  return "default"
}

